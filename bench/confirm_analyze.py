"""Runs the PREREG.md analysis once on E1-E3 output. Writes results/confirm.json
and paper/confirm_numbers.tex (\\C{key} macros for the paper).
Usage: python3 bench/confirm_analyze.py"""
import json
import os
import statistics
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "bench"))
import paired  # noqa: E402

R = os.path.join(ROOT, "results")


def e1():
    r1 = json.load(open(os.path.join(R, "rerun-2026-11-20", "route1.json")))
    out = {"e1a": {ph: {c: {k: r1[ph][c][k] for k in ("n", "median_ms", "median_ci95", "p75_ms", "mean_ms")} for c in r1[ph]}
                   for ph in ("cold", "warm")}}
    rows = json.load(open(os.path.join(R, "rerun-2026-11-20", "route3_rows.json")))
    by = {}
    for x in rows:
        by.setdefault((x["round"], x["host"]), {})[x["mode"]] = x
    def ok(x):
        return x and x.get("code") and 100 <= x["code"] < 600 and x.get("total_ms") is not None
    pairs = {k: v for k, v in by.items() if ok(v.get("on")) and ok(v.get("off"))}
    warm = [v["on"]["total_ms"] - v["off"]["total_ms"] for (rnd, _), v in pairs.items() if rnd >= 2]
    cold = [v["on"]["total_ms"] - v["off"]["total_ms"] for (rnd, _), v in pairs.items() if rnd == 1]
    out["e1b"] = {"dropped_units": len(by) - len(pairs), "warm": paired.summary(warm), "cold": paired.summary(cold),
                  "off_median_ms": round(statistics.median(v["off"]["total_ms"] for (rnd, _), v in pairs.items() if rnd >= 2), 1)}
    return out


def e3():
    rows = [json.loads(l) for l in open(os.path.join(R, "habit.jsonl"))]
    bad = {r["site"] for r in rows if "error" in r}
    sites = {}
    for r in rows:
        if "error" not in r and r["site"] not in bad:
            sites.setdefault(r["site"], {}).setdefault(r["ext"], []).append(r)
    sites = {s: a for s, a in sites.items() if len(a.get("on", [])) and len(a.get("off", []))}
    med = lambda xs, k: statistics.median(x[k]["waited"] for x in xs)  # noqa: E731
    nxt = [med(a["on"], "next") - med(a["off"], "next") for a in sites.values()]
    home = [med(a["on"], "home") - med(a["off"], "home") for a in sites.values()]
    on_rows = [x for a in sites.values() for x in a["on"]]
    pre = sum(x["next"]["activationStart"] > 0 or x["next"]["deliveryType"] in ("navigational-prefetch",) for x in on_rows)
    prerendered = sum(x["next"]["activationStart"] > 0 for x in on_rows)
    return {"sites": len(sites), "dropped_sites": len({r["site"] for r in rows}) - len(sites),
            "next": paired.summary(nxt), "home": paired.summary(home),
            "off_next_median_ms": round(statistics.median(med(a["off"], "next") for a in sites.values()), 1),
            "on_next_median_ms": round(statistics.median(med(a["on"], "next") for a in sites.values()), 1),
            "on_measured": len(on_rows), "on_served_preloaded": pre, "on_prerendered": prerendered}


def main():
    out = e1()
    out["e2"] = json.load(open(os.path.join(R, "dns_sim.json")))
    out["e3"] = e3()
    ps = [out["e1b"]["warm"]["p"], out["e2"]["primary_P_minus_S_per_day"]["p"], out["e3"]["next"]["p"]]
    out["holm"] = dict(zip(("e1b", "e2", "e3"), paired.holm(ps)))
    json.dump(out, open(os.path.join(R, "confirm.json"), "w"), indent=1)

    flat = {}
    def walk(pre, v):
        if isinstance(v, dict):
            for k, x in v.items():
                walk(pre + "." + k if pre else k, x)
        elif isinstance(v, list) and len(v) == 2 and all(isinstance(z, (int, float)) for z in v):
            walk(pre + ".lo", v[0]); walk(pre + ".hi", v[1])
        elif isinstance(v, float):
            flat[pre] = ("%.2g" % v) if (k := pre.split(".")[-1]) == "p" or pre.startswith("holm") else ("%.1f" % v if abs(v) >= 1 or v == 0 else "%.2f" % v)
        elif isinstance(v, int):
            flat[pre] = "{:,}".format(v).replace(",", "{,}")
    walk("", out)
    with open(os.path.join(ROOT, "paper", "confirm_numbers.tex"), "w") as f:
        f.write("% generated by bench/confirm_analyze.py from results/confirm.json\n")
        for k, v in sorted(flat.items()):
            f.write("\\expandafter\\def\\csname c@%s\\endcsname{%s}\n" % (k, v))
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
