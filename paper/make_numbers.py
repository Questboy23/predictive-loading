"""Reads the machine-readable block of RESULTS.md and writes numbers.tex
(\V{key} macros) plus the grayscale charts. The paper takes every number from here."""
import os
import re
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
text = open(os.path.join(HERE, "..", "RESULTS.md")).read()
block = text.split("## Machine-readable values")[1].split("```")[1]
V = {}
for line in block.strip().splitlines():
    k, v = line.split(" = ", 1)
    V[k.strip()] = v.strip()

with open(os.path.join(HERE, "numbers.tex"), "w") as f:
    f.write("% generated by make_numbers.py from RESULTS.md\n")
    for k, v in sorted(V.items()):
        f.write("\\expandafter\\def\\csname v@%s\\endcsname{%s}\n" % (k, v.replace("%", "\\%").replace(",", "{,}")))
print("numbers.tex: %d values" % len(V))

plt.rcParams.update({"font.family": "serif", "font.size": 9, "axes.edgecolor": "black", "axes.labelcolor": "black",
                     "xtick.color": "black", "ytick.color": "black"})
GRAYS = ["0.0", "0.35", "0.6", "0.8", "1.0"]
HATCH = ["", "//", "", "..", "xx"]


def bars(ax, groups, series, getter, ylabel):
    width = 0.8 / len(series)
    for j, (sname, skey) in enumerate(series):
        xs, ys = [], []
        for i, (gname, gkey) in enumerate(groups):
            v = getter(gkey, skey)
            if v is not None:
                xs.append(i + j * width - 0.4 + width / 2)
                ys.append(v)
        ax.bar(xs, ys, width, label=sname, color=GRAYS[j % 5], edgecolor="black", hatch=HATCH[j % 5], linewidth=0.6)
    ax.set_xticks(range(len(groups)))
    ax.set_xticklabels([g[0] for g in groups])
    ax.set_ylabel(ylabel)
    ax.legend(frameon=False, fontsize=7)


def num(k):
    try:
        return float(V[k].replace(",", ""))
    except KeyError:
        return None


# Route 0: bits per event by trace and method
traces = [("MSNBC", "msnbc"), ("NASA", "nasa_jul95"), ("ClarkNet", "clarknet_aug28"), ("Wikisp.", "wikispeedia"),
          ("Rec. dom.", "recorded_chrome_domains"), ("Rec. paths", "recorded_chrome_paths_per_origin")]
methods = [("Mixture", "mixture"), ("PPM-C", "ppm_c"), ("Markov-1", "markov1"), ("Most popular", "most_popular")]
fig, axs = plt.subplots(1, 2, figsize=(6.5, 2.4))
bars(axs[0], traces, methods, lambda t, m: num("r0.%s.%s.bits" % (t, m)), "bits per event (lower better)")
bars(axs[1], traces, methods + [("Last succ.", "last_successor")], lambda t, m: num("r0.%s.%s.top1" % (t, m)), "top-1 hit rate (%)")
for ax in axs:
    ax.tick_params(axis="x", labelsize=7, rotation=30)
fig.tight_layout()
fig.savefig(os.path.join(HERE, "fig_route0.pdf"))

# Route 1: DNS median by condition
conds = [("System", "system_default"), ("Unbound", "unbound_alone"), ("Unbound+pred.", "unbound_plus_predictor")]
fig, ax = plt.subplots(figsize=(3.2, 2.2))
bars(ax, conds, [("cold (round 1)", "cold"), ("later rounds", "warm")], lambda c, p: num("r1.%s.%s.median_ms" % (p, c)), "median lookup ms")
fig.tight_layout()
fig.savefig(os.path.join(HERE, "fig_route1.pdf"))

# Route 2: next-page wait and home load by Wi-Fi profile
profiles = [("home 10 ms", 10), ("campus 60 ms", 60), ("poor 150 ms", 150)]
cells = [("ext off, Mac off", ("off", "off")), ("ext off, Mac on", ("off", "on")), ("ext on, Mac off", ("on", "off")), ("ext on, Mac on", ("on", "on"))]
if num("r2.n"):
    fig, axs = plt.subplots(1, 2, figsize=(6.5, 2.4))
    bars(axs[0], profiles, cells, lambda r, c: num("r2.%d.%s.%s.home" % (r, c[0], c[1])), "home page load, median ms")
    bars(axs[1], profiles, cells, lambda r, c: num("r2.%d.%s.%s.next" % (r, c[0], c[1])), "wait for next page, median ms")
    fig.tight_layout()
    fig.savefig(os.path.join(HERE, "fig_route2.pdf"))
